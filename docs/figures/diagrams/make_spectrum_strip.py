    band(s, ax, Y_BAND, H_BAND)
    if dim is not None:
        for lo, hi in dim["spans"]:  # the chapter's span, drawn as a brace around the band
            s.rect(ax.x(min(lo, ax.left_nm)), Y_BAND - 4, ax.x(max(hi, ax.right_nm)) - ax.x(min(lo, ax.left_nm)), H_BAND + 8,
                   fill="none", stroke="hue:history", sw=1.8, rx=5)
