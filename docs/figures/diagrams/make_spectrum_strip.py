def optic_icon(s: K.Svg, kind: str, cx: float, cy: float, *, opacity: float = 1.0) -> None:
    """20-unit pictograms: lens, lens + water drop, dashed CaF₂ lens, Mo/Si stack, hollow La/B stack, zone plate."""
    with s.group(opacity=opacity):
        if kind.startswith("lens"):
            dash = "3 2" if kind == "lens-dashed" else None
            fill = "none" if kind == "lens-dashed" else s.t["material"]["glass"]
            d = f"M{K.fmt(cx)},{K.fmt(cy - 12)} Q{K.fmt(cx + 9)},{K.fmt(cy)} {K.fmt(cx)},{K.fmt(cy + 12)} Q{K.fmt(cx - 9)},{K.fmt(cy)} {K.fmt(cx)},{K.fmt(cy - 12)} Z"
            s.path(d, fill=fill, stroke=s.t["material_stroke"]["glass"], sw=1.4, dash=dash)
            if kind == "lens-water":
                s.ellipse(cx, cy + 15, 9, 3.5, fill=s.t["material"]["water"], stroke=s.t["material_stroke"]["water"], sw=1.0)
        elif kind.startswith("ml"):
            hollow = kind == "ml-hollow"
            for i in range(6):
                yy = cy - 11 + i * 4
                s.rect(cx - 11, yy, 22, 3, fill="none" if hollow else (s.t["material"]["mirror"] if i % 2 else s.t["material"]["substrate"]),
                       stroke=s.t["material_stroke"]["mirror"] if hollow else "none", sw=0.8, dash="2 1.5" if hollow else None)
            s.line(cx - 14, cy + 15, cx - 4, cy + 1, "ink2", 1.0, arrow="end")
            s.line(cx + 4, cy + 1, cx + 14, cy + 15, "ink2", 1.0, arrow="end")
        else:  # zone plate: concentric rings
            for r in (11, 8, 5, 2.5):
                s.circle(cx, cy, r, fill="none", stroke="ink2", sw=1.2)


def optics_row(s: K.Svg, ax: Axis, y_icon: float, *, dim: dict | None = None, caption_y: float, note: bool = False) -> None:
    items = []
    for kind, lam, cap, nt in OPTICS:
        x = ax.x(lam)
        w = K.text_width(cap, 12.5)
        items.append((kind, lam, cap, nt, x, w))
    lanes = allocate_lanes([(it[4] - it[5] / 2, it[4] + it[5] / 2) for it in items], gap=6, max_lanes=2)
    for (kind, lam, cap, nt, x, w), ln in zip(items, lanes):
        op = 1.0 if dim is None or any(hi <= lam <= lo for lo, hi in dim["spans"]) else 0.35
        optic_icon(s, kind, x, y_icon, opacity=op)
        yy = caption_y + ln * 15
        s.text(x, yy, cap, size=12.5, color="ink2", opacity=op)
        if note:
            s.text(x, yy + 15 * (2 - ln), nt, size=12.5, color="muted", opacity=op)


def optics_grid(s: K.Svg, x0: float, x1: float, y: float, *, dim: dict | None = None, cols: int = 3,
                row_h: float = 74.0) -> float:
    """The optic per band as a grid of pictogram · caption · band note (the narrow twins: on a 400-unit canvas
    the pictograms would collide on the axis); returns the y below the grid."""
    cw = (x1 - x0) / cols
    for k, (kind, lam, cap, nt) in enumerate(OPTICS):
        r, c = divmod(k, cols)
        cx, cy = x0 + (c + 0.5) * cw, y + r * row_h
        op = 1.0 if dim is None or any(hi <= lam <= lo for lo, hi in dim["spans"]) else 0.35
        optic_icon(s, kind, cx, cy + 18, opacity=op)
        s.text(cx, cy + 48, cap, size=12.5, color="ink2", opacity=op)
        s.text(cx, cy + 64, nt, size=12.5, color="muted", opacity=op)
    return y + ((len(OPTICS) - 1) // cols + 1) * row_h


def era_pills(s: K.Svg, ax: Axis, y: float, years: dict[str, int], *, lit: set[str] | None = None,
              cls_prefix: str | None = None, dim_opacity: float = 0.35, lane_h: float = 23.0,
              max_lanes: int = 3, x_min: float | None = None, x_max: float | None = None) -> dict[str, tuple[float, float, float, int]]:
    """Era pills at their λ in greedy lanes; returns {label: (x, y, w, lane)}. With ``x_min``/``x_max`` a pill
    that would cross the canvas edge is shifted inside and its leader runs from the λ to the pill."""
    items = []
    for i, (label, lam, _t) in enumerate(ERAS):
        if label not in years:
            continue
        txt = f"{label} · {years[label]}"
        w = K.text_width(txt, 12.5, 600) + 16
        x = ax.x(lam)
        px = x
        if x_min is not None:
            px = max(px, x_min + w / 2)
        if x_max is not None:
            px = min(px, x_max - w / 2)
        items.append((i, label, txt, x, px, w))
    lanes = allocate_lanes([(px - w / 2, px + w / 2) for (_i, _l, _t, _x, px, w) in items], gap=6, max_lanes=max_lanes)
    placed: dict[str, tuple[float, float, float, int]] = {}
    rows = []
    for (i, label, txt, x, px, w), ln in zip(items, lanes):
        py = y + ln * lane_h
        op = 1.0 if (lit is None or label in lit) else dim_opacity
        cls = f"{cls_prefix}{i}" if cls_prefix else None
        rows.append((cls, op, x, px, py, w, txt))
        placed[label] = (px, py, w, ln)
    for cls, op, x, px, py, w, txt in rows:  # leaders first …
        with s.group(cls, opacity=None if cls else op):
            s.line(x, y - 10, px, py, "axis", 1.0)
    for cls, op, _x, px, py, w, txt in rows:  # … then the pills, whose opaque fill hides any leader crossing them
        with s.group(cls, opacity=None if cls else op):
            s.rect(px - w / 2, py, w, 20, fill=s.tint("hue:history", 0.10), stroke="hue:history", sw=1.0, rx=10)
            s.text(px, py + 14, txt, size=12.5, color="ink", weight=600)
    return placed


