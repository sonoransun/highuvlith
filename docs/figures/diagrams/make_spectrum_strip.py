def draw_bands(theme: str) -> str:
    presets = load_presets()
    rows = [(n, lo, hi, note) for n, lo, hi, note, _k in OPTICS_BANDS if lo > 1.0] + [(n, lo, hi, "CLI auto-pick band") for n, lo, hi in SCHWARZSCHILD_BANDS]
    rows.append(("Fresnel zone plate (diffractive)", 250.0, 1.0, "any wavelength; chromatic defocus applied once"))
    y0, step = 90, 28
    H = y0 + len(rows) * step + 62
    s = K.Svg(W, H, theme, "Conventional optics bands", BANDS_ALT, generator=GENERATOR)
    ax = Axis(60, 900, segments=((250.0, 1.0, 1.0),))
    yb, hb = 40, 10
    s.eyebrow(60, 18, "Which optic is physical where — conventional use, not enforced by the engine", size=12.5)
    band(s, ax, yb, hb, breaks=False)
    for lam, lab in ((250, "250 nm"), (100, "100"), (50, "50"), (20, "20"), (10, "10"), (5, "5"), (2, "2"), (1, "1 nm")):
        x = ax.x(lam)
        s.line(x, yb + hb + 2, x, yb + hb + 6, "axis", 1.0)
        s.text(x, yb + hb + 18, lab, size=12.5, color="muted")
    for p in presets["presets"]:
        lam = p["wavelength_nm"]
        if 1.0 <= lam <= 250.0:
            x = ax.x(lam)
            s.line(x, yb - 6, x, yb - 1, "ink", 1.0)
    y_end = y0 + len(rows) * step
    for k, (lam, label, col) in enumerate(((GUI_SWITCH_NM, "GUI switches to EUV optics below 110 nm", "hue:future"),
                                            (CLI_WARN_NM, "CLI warns: refractive below 50 nm", "hue:history"))):
        x = ax.x(lam)
        s.line(x, yb - 8, x, y_end - 6 + 16 * k, col, 1.4, dash="5 3")
        s.text(x + 5, y_end + 6 + 16 * k, label, size=12.5, anchor="start", color=col, halo=True)
    y = y0
    for name, lo, hi, note in rows:
        x1, x2 = ax.x(min(lo, 250.0)), ax.x(max(hi, 1.0))
        hollow = name.startswith("Fresnel")
        s.rect(x1, y, max(x2 - x1, 3), 12, fill="none" if hollow else s.tint("hue:simulator", 0.25), stroke="hue:simulator",
               sw=1.0, rx=3, dash="4 3" if hollow else None)
        text = f"{name} — {note}"
        tw = K.text_width(text, 12.5)
        tx = max(x1, ax.x0 + 2)
        if tx + tw > ax.x1:  # a bar near the right edge: hang the label from the bar's right end instead
            s.text(min(x2, ax.x1), y - 4, text, size=12.5, anchor="end", color="ink2", halo=True)
        else:
            s.text(tx, y - 4, text, size=12.5, anchor="start", color="ink2", halo=True)
        y += step
    s.text(60, H - 10, "Ticks above the band are the source presets' wavelengths. Pick the optic that is physical for your source; the math will image anything.",
           size=12.5, anchor="start", color="ink2")
    return s.render()


def draw_ladder(theme: str) -> str:
    rungs = load_rungs()
    years = era_years()
    H = 296
    s = K.Svg(W, H, theme, "From 436 nm to 1 nm", LADDER_ALT, generator=GENERATOR)
    ax = Axis(60, 900, segments=((500.0, 100.0, 0.40), (100.0, 0.8, 0.60)))
    yb, hb = 58, 10
    band(s, ax, yb, hb)
    ruler(s, ax, yb + hb + 6, labels=(500, 100, 10, 1), energy=True)
    year_of = {"g-line": years.get("g-line"), "i-line": years.get("i-line"), "KrF": years.get("KrF")}
    items = [(label, ax.x(lam), K.text_width(label, 12.5, 600)) for label, lam, *_ in rungs]
    lanes = allocate_lanes([(x - w / 2, x + w / 2) for _l, x, w in items], gap=8, max_lanes=3)
    chip_items = []
    for (label, lam, optic, rung, style, _src), (_l, x, w), ln in zip(rungs, items, lanes):
        yy = 38 - ln * 14
        s.line(x, yb - 4, x, yb + hb + 3, "ink", 1.2, dash="3 2" if style == "dashed" else None)
        if ln > 0:
            s.line(x, yy + 3, x, yb - 5, "axis", 0.8, opacity=0.8)
        chip_items.append((label, x, optic, rung, style, yy))
    for label, x, _optic, _rung, _style, yy in chip_items:  # labels over every leader
        s.text(x, yy, label, size=12.5, color="ink", weight=600, halo=True)
    # optics under the rungs (one icon per distinct position)
    seen_x: list[float] = []
    for label, x, optic, rung, style, _yy in chip_items:
        if any(abs(x - sx) < 16 for sx in seen_x):
            continue
        seen_x.append(x)
        optic_icon(s, optic, x, 150, opacity=0.5 if style == "dashed" else 1.0)
    # rung chips / years in lanes
    texts = []
    for label, x, optic, rung, style, _yy in chip_items:
        if rung:
            w = K.text_width(rung, 12.5 * 0.9, 600) + 16
            texts.append((label, x, w, rung, True, style))
        elif year_of.get(label):
            t = f"first tool {year_of[label]}"
            texts.append((label, x, K.text_width(t, 12.5), t, False, style))
        elif label.startswith("F₂"):
            t = "no production tool"
            texts.append((label, x, K.text_width(t, 12.5), t, False, style))
    lanes2 = allocate_lanes([(x - w / 2, x + w / 2) for _l, x, w, _t, _c, _s in texts], gap=8, max_lanes=4)
    for (label, x, w, t, is_chip, style), ln in zip(texts, lanes2):
        if ln > 0:
            s.line(x, 168, x, 190 + ln * 22 - 10, "axis", 0.8, opacity=0.8)
    for (label, x, w, t, is_chip, style), ln in zip(texts, lanes2):
        y = 190 + ln * 22
        if is_chip:
            K.chip(s, x, y, t, size=12.5, anchor="middle", outlined=True)
        else:
            s.text(x, y + 4, t, size=12.5, color="ink2", italic=not t.startswith("first"), halo=True)
    s.text(60, H - 22, "Rung words follow the Future section's readiness ladder (September 2026): hollow = announced, dashed = speculative.",
           size=12.5, anchor="start", color="ink2")
    s.text(60, H - 8, "Years are first tool models in litho_tools.csv; the log axis is expanded above 100 nm (break marked).",
           size=12.5, anchor="start", color="ink2")
    return s.render()


