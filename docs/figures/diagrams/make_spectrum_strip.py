def check() -> tuple[list[str], list[str]]:
    errors: list[str] = []
    warnings: list[str] = []
    if not DATA.exists():
        errors.append(f"spectrum-strip: {registry.rel_to_repo(DATA)} missing (run --refresh)")
        return errors, warnings
    data = load_presets()
    for p in data["presets"]:
        row = matrix_parse.find(p["row"])
        if row is None:
            errors.append(f"spectrum-strip: presets.json row {p['row']!r} is not a matrix row")
        elif row.headline != p["badge"]:
            errors.append(f"spectrum-strip: presets.json badge for {p['factory']} is {p['badge']} but the matrix says {row.headline} (run --refresh)")
        if p["setting"] not in SETTING_GLYPH:
            errors.append(f"spectrum-strip: unknown setting {p['setting']!r} for {p['factory']}")
    try:
        fresh = refresh_presets()
        if fresh["presets"] != data["presets"]:
            errors.append("spectrum-strip: data/presets.json differs from the engine's presets (run --refresh)")
    except ImportError:
        warnings.append("spectrum-strip: extension not importable; presets.json freshness not checked")
    for label, _lam, _t in ERAS:
        if label not in era_years():
            warnings.append(f"spectrum-strip: era {label!r} has no tool in litho_tools.csv")
    for _label, _lam, _optic, rung, _style, _src in load_rungs():
        if rung is not None and rung not in tokens.RUNGS:
            errors.append(f"spectrum-strip: rung word {rung!r} is not an Appendix B word")
    return errors, warnings


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if "--refresh" in argv:
        data = refresh_presets()
        DATA.parent.mkdir(parents=True, exist_ok=True)
        DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"wrote {registry.rel_to_repo(DATA)} ({len(data['presets'])} presets)")
        return 0
    if "--check" in argv:
        e, w = check()
        for x in w:
            print("warning:", x)
        for x in e:
            print("error:", x)
        print(f"spectrum-strip check: {len(e)} error(s), {len(w)} warning(s)")
        return 1 if e else 0
    only = [a for a in argv if not a.startswith("--")]
    for key, fn in GENERATORS.items():
        if only and not any(o in key for o in only):
            continue
        for p in fn():
            print(f"wrote {registry.rel_to_repo(p)} ({p.stat().st_size / 1024:.1f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
