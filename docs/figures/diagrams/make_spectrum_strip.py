def load_tools() -> list[dict]:
    rows = []
    with TOOLS_CSV.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows.append({
                "year": int(r["year"]),
                "wavelength_nm": float(r["wavelength_nm"]) if r["wavelength_nm"] else None,
                "na": float(r["na"]) if r["na"] else None,
                "optics": r["optics"],
                "model": r["model"],
            })
    return rows


def era_years(tools: list[dict] | None = None) -> dict[str, int]:
    """First tool-model year per era class (the lanes rule)."""
    tools = tools or load_tools()
    out = {}
    for label, _lam, test in ERAS:
        years = [t["year"] for t in tools if test(t)]
        if years:
            out[label] = min(years)
    return out


def family_of(kind: str, factory: str) -> str:
    return "heritage" if kind == "vuv" and factory in HERITAGE else kind


