def _ruler_groups(presets: dict) -> list[dict]:
    """Presets grouped per family: one label + chip per family, every preset λ as a glyph."""
    groups: dict[str, dict] = {}
    for p in presets["presets"]:
        g = groups.setdefault(p["family"], {"family": p["family"], "row": p["row"], "lams": [], "spans": [], "setting": p["setting"]})
        if p["span_nm"]:
            g["spans"].append((p["span_nm"], p["provenance"]))
        g["lams"].append((p["wavelength_nm"], p["provenance"]))
    out = list(groups.values())
    for g in out:
        xs = [l for l, _p in g["lams"]] + [x for sp, _p in g["spans"] for x in sp]
        g["lo"], g["hi"] = max(xs), min(xs)
        g["mid"] = 10 ** ((math.log10(g["lo"]) + math.log10(g["hi"])) / 2)
    out.sort(key=lambda g: -g["lo"])
    return out


def _glyph(s: K.Svg, kind: str, x: float, y: float, filled: bool, color: str, r: float = 4.5) -> None:
    f = color if filled else "none"
    if kind == "derived":  # ◆
        s.add(f'<path d="M{K.fmt(x)},{K.fmt(y - r)} L{K.fmt(x + r)},{K.fmt(y)} L{K.fmt(x)},{K.fmt(y + r)} L{K.fmt(x - r)},{K.fmt(y)} Z" fill="{f}" stroke="{color}" stroke-width="1.3"/>')
    elif kind == "set-point":  # ●
        s.circle(x, y, r, fill=f, stroke=color, sw=1.3)
    elif kind == "fixed":  # ▲
        s.add(f'<path d="M{K.fmt(x)},{K.fmt(y - r)} L{K.fmt(x + r)},{K.fmt(y + r)} L{K.fmt(x - r)},{K.fmt(y + r)} Z" fill="{f}" stroke="{color}" stroke-width="1.3"/>')
    else:  # ■
        s.rect(x - r, y - r, 2 * r, 2 * r, fill=f, stroke=color, sw=1.3)


def _ruler_rows(s: K.Svg, ax: Axis, presets: dict, *, y_top: float, lane_h: float, max_lanes: int, bands_y: float,
                compact: bool = False, band_y: float | None = None) -> None:
    """Family labels + chips in lanes; the cluster at 13.5 nm fans out sideways with leader lines. Only the
    presets and bands inside the axis range are drawn (the narrow twin splits the axis at 100 nm); ``band_y``
    is where the glyph leaders start."""
    groups = [g for g in _ruler_groups(presets)
              if any(ax.inside(lam) for lam, _p in g["lams"]) or any(ax.inside(lo) or ax.inside(hi) for (lo, hi), _p in g["spans"])]
    if band_y is None:
        band_y = Y_BAND + H_BAND + 2 if y_top > 100 else 62
    color = s.t["hues"]["simulator"]
    cursors = [-1e9] * max_lanes
    gap = 14
    y_glyph = y_top - 14
    labels: list[tuple[float, float, str, str, float]] = []
    for g in groups:
        label = FAMILY_LABEL[g["family"]]
        row = matrix_parse.find(g["row"])
        slug = row.slug if row else "implemented"
        lw = K.text_width(label, 12.5, 600)
        chip_w = 0.4 * 12.5 + 12.5 * 0.9 + 0.55 * 12.5 + (0 if compact else 0.3 * 12.5 + K.text_width(tokens.GRADES[slug][1], 12.5, 600))
        total = lw + 8 + chip_w
        x_mid = ax.x(g["mid"])
        want = x_mid - total / 2
        free = [i for i in range(max_lanes) if cursors[i] + gap <= want]
        if free:  # a lane where the label sits exactly under its glyph
            lane = free[0]
        else:  # every lane is occupied there: take the least advanced lane and fan out to the right
            lane = min(range(max_lanes), key=lambda i: cursors[i])
        left = max(cursors[lane] + gap, want)
        left = max(ax.x0 - 24, 8, left)
        cursors[lane] = left + total
        y = y_top + lane * lane_h
        for lam, prov in g["lams"]:
            if not ax.inside(lam):
                continue
            x = ax.x(lam)
            s.line(x, band_y, x, y_glyph - 6, "axis", 0.7, opacity=0.6)
            _glyph(s, g["setting"], x, y_glyph, prov == "measured", color)
        for (lo, hi), prov in g["spans"]:
            s.line(ax.x(_clamp_nm(ax, lo)), y_glyph, ax.x(_clamp_nm(ax, hi)), y_glyph, color, 2.2, opacity=0.8,
                   dash=None if prov == "measured" else "3 3")
        # leader from the family's glyph position to its label when the label was pushed sideways
        if abs((left + total / 2) - x_mid) > 12:
            s.line(x_mid, y_glyph + 7, left + 2, y + 3, "axis", 0.8, opacity=0.9)
        labels.append((left, y, label, slug, lw))
    for left, y, label, slug, lw in labels:  # labels after every leader, haloed, so no leader cuts a name
        s.text(left, y + 11, label, size=12.5, anchor="start", color="ink", weight=600, halo=True)
        K.chip(s, left + lw + 8, y + 7, slug, size=12.5, word=not compact)
    for i, (name, lo, hi, _note, _kind) in enumerate(OPTICS_BANDS):
        if lo <= ax.right_nm or hi >= ax.left_nm:  # entirely outside this axis range
            continue
        x1, x2 = ax.x(min(lo, ax.left_nm)), ax.x(max(hi, ax.right_nm))
        s.rect(x1, bands_y, max(x2 - x1, 3), 10, fill=s.tint("hue:simulator", 0.18), stroke="none", rx=2)
        wide = x2 - x1 > 90
        s.text((x1 + x2) / 2 if wide else x1 + 2, bands_y + 24 + (0 if wide else 14 * (i % 2)), name, size=12.5,
               color="ink2", anchor="middle" if wide else "start")


